Он лишь готовит выборку и возвращает Cursor.

Cursor нужен, чтобы:
экономить память,
обрабатывать данные по одной записи,
работать с очень большими таблицами,
иметь возможность досрочно остановить итерацию и освободить ресурсы (close()).*/